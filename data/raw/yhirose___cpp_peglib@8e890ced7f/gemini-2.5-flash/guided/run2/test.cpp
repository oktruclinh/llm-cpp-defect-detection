TEST(EnableAstTest, MultipleCallsToEnableAst) {
    peg::parser parser(R"(
        ROOT <- A B
        A <- 'a'
        B <- 'b'
    )");

    ASSERT_TRUE(parser.valid());

    // First call with default Ast
    parser.enable_ast();

    // Second call with custom Ast type
    parser.enable_ast<CustomAstNode>();

    // Set the custom AST builder
    parser.set_ast_builder(custom_ast_builder);

    std::shared_ptr<CustomAstNode> custom_ast;
    bool ret = parser.parse("ab", custom_ast);

    ASSERT_TRUE(ret);
    ASSERT_NE(custom_ast, nullptr);
    ASSERT_EQ(custom_ast->name, "ROOT");
    ASSERT_EQ(custom_ast->children.size(), 2);
    ASSERT_EQ(custom_ast->children[0].name, "A");
    ASSERT_EQ(custom_ast->children[1].name, "B");

    // Verify that the actions are correctly set for the custom type
    // This implies that the last enable_ast call takes precedence for rules without existing actions.
    // The internal mechanism of enable_ast is to add an action IF one doesn't exist.
    // So, the first call adds default Ast actions. The second call, if it finds an existing action,
    // will not overwrite it. However, the type parameter T in enable_ast<T> affects the type
    // of AST node created by the default action, which is then passed to the ast_builder.
    // The key is that the ast_builder is set globally for the parser.
}

TEST(EnableAstTest, EnableAstThenDisableAst) {
    peg::parser parser(R"(
        ROOT <- A B
        A <- 'a'
        B <- 'b'
    )");

    ASSERT_TRUE(parser.valid());

    parser.enable_ast();

    // Disabling AST should remove the default AST actions
    parser.disable_ast();

    std::shared_ptr<peg::Ast> ast;
    bool ret = parser.parse("ab", ast);

    ASSERT_TRUE(ret); // Parsing should still succeed
    ASSERT_EQ(ast, nullptr); // No AST should be generated
}

TEST(EnableAstTest, EnableAstThenDisableAstThenEnableAgain) {
    peg::parser parser(R"(
        ROOT <- A B
        A <- 'a'
        B <- 'b'
    )");

    ASSERT_TRUE(parser.valid());

    parser.enable_ast();
    parser.disable_ast();
    parser.enable_ast(); // Enable again

    std::shared_ptr<peg::Ast> ast;
    bool ret = parser.parse("ab", ast);

    ASSERT_TRUE(ret);
    ASSERT_NE(ast, nullptr); // AST should be generated again
    ASSERT_EQ(ast->name, "ROOT");
}

TEST(EnableAstTest, GrammarWithRecursion) {
    peg::parser parser(R"(
        EXPR <- TERM (('+' / '-') TERM)*
        TERM <- FACTOR (('*' / '/') FACTOR)*
        FACTOR <- NUMBER / '(' EXPR ')'
        NUMBER <- [0-9]+
    )");

    ASSERT_TRUE(parser.valid());

    parser.enable_ast();

    std::shared_ptr<peg::Ast> ast;
    bool ret = parser.parse("1 + 2 * (3 - 4)", ast);

    ASSERT_TRUE(ret);
    ASSERT_NE(ast, nullptr);
    ASSERT_EQ(ast->name, "EXPR");
    ASSERT_EQ(ast->nodes.size(), 3); // TERM, '+', TERM
    ASSERT_EQ(ast->nodes[0]->name, "TERM");
    ASSERT_EQ(ast->nodes[1]->token, "+");
    ASSERT_EQ(ast->nodes[2]->name, "TERM");
    ASSERT_EQ(ast->nodes[2]->nodes.size(), 3); // FACTOR, '*', FACTOR
    ASSERT_EQ(ast->nodes[2]->nodes[0]->name, "FACTOR");
    ASSERT_EQ(ast->nodes[2]->nodes[0]->nodes[0]->name, "NUMBER");
    ASSERT_EQ(ast->nodes[2]->nodes[0]->nodes[0]->token, "2");
}