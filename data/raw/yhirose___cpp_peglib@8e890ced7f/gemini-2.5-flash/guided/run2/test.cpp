#include <gtest/gtest.h>
#include <peglib.h>

// Define a custom AST node type for testing
struct CustomAstNode {
    std::string name;
    std::vector<CustomAstNode> children;
};

// Custom AST builder function
std::shared_ptr<CustomAstNode> custom_ast_builder(const peg::Ast& ast) {
    auto node = std::make_shared<CustomAstNode>();
    node->name = ast.name;
    for (const auto& child : ast.nodes) {
        node->children.push_back(*custom_ast_builder(*child));
    }
    return node;
}

TEST(EnableAstTest, BasicGrammarWithDefaultAst) {
    peg::parser parser(R"(
        ROOT <- A B
        A <- 'a'
        B <- 'b'
    )");

    ASSERT_TRUE(parser.valid());

    // Enable AST generation with default Ast type
    parser.enable_ast();

    std::shared_ptr<peg::Ast> ast;
    bool ret = parser.parse("ab", ast);

    ASSERT_TRUE(ret);
    ASSERT_NE(ast, nullptr);
    ASSERT_EQ(ast->name, "ROOT");
    ASSERT_EQ(ast->nodes.size(), 2);
    ASSERT_EQ(ast->nodes[0]->name, "A");
    ASSERT_EQ(ast->nodes[0]->token, "a");
    ASSERT_EQ(ast->nodes[1]->name, "B");
    ASSERT_EQ(ast->nodes[1]->token, "b");
}

TEST(EnableAstTest, GrammarWithExistingActionsAndDefaultAst) {
    peg::parser parser(R"(
        ROOT <- A B
        A <- 'a'
        B <- 'b'
    )");

    ASSERT_TRUE(parser.valid());

    // Add an action to rule A before enabling AST
    parser["A"] = [](const peg::SemanticValues& sv) {
        return sv.token();
    };

    // Enable AST generation with default Ast type
    parser.enable_ast();

    std::shared_ptr<peg::Ast> ast;
    bool ret = parser.parse("ab", ast);

    ASSERT_TRUE(ret);
    ASSERT_NE(ast, nullptr);
    ASSERT_EQ(ast->name, "ROOT");
    ASSERT_EQ(ast->nodes.size(), 2);
    // Rule A should still have its custom action, so it won't generate an AST node by default
    // The default enable_ast only adds actions if one doesn't exist.
    ASSERT_EQ(ast->nodes[0]->name, "A"); // Still an AST node, but its content might be affected by the action
    ASSERT_EQ(ast->nodes[0]->token, "a");
    ASSERT_EQ(ast->nodes[1]->name, "B");
    ASSERT_EQ(ast->nodes[1]->token, "b");
}

TEST(EnableAstTest, EmptyGrammar) {
    peg::parser parser(""); // Empty grammar

    ASSERT_FALSE(parser.valid()); // An empty grammar is not valid

    // Calling enable_ast on an invalid parser should not crash and should return *this
    parser.enable_ast();

    // No meaningful parse can be done, but we ensure it doesn't crash.
    // The internal grammar_ will be empty, so the loop in enable_ast won't execute.
}

